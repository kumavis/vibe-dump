// End-to-end checks against the production bundle, without physical hardware.
import assert from 'node:assert/strict'
import { fileURLToPath } from 'node:url'
import { chromium } from 'playwright'
import { startStaticServer } from '../../../scripts/static-server.mjs'

const server = await startStaticServer(fileURLToPath(new URL('../dist/', import.meta.url)))
let browser
try {
  browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.addInitScript(() => {
    window.testPads = []
    Object.defineProperty(navigator, 'getGamepads', { value: () => window.testPads })
    const raf = window.requestAnimationFrame
    window.requestAnimationFrame = cb => window.freezeFrames ? 0 : raf(cb)
  })
  await page.goto(server.url + '/?god')
  await page.waitForFunction(() => window.__step && !document.getElementById('boot'), null, { timeout: 120000 })
  await page.evaluate(() => { window.freezeFrames = true })
  await page.waitForTimeout(100)
  const run = fn => page.evaluate(fn)
  const tick = () => run(() => __step(1 / 60, 1 / 60))
  const button = async (i, held = true) => {
    await page.evaluate(({ i, held }) => { testPads[0].buttons[i] = { pressed: held, value: held ? 1 : 0 }; __step(1 / 60, 1 / 60) }, { i, held })
  }
  const tap = async i => { await button(i); await button(i, false) }
  await run(() => {
    testPads = [{ id: 'Xbox Wireless Controller', index: 0, mapping: 'standard', connected: true, axes: [0, 0, 0, 0], buttons: Array.from({ length: 17 }, () => ({ value: 0, pressed: false })) }]
  })
  await tick()
  assert.equal(await run(() => __G.input.focused), true)
  await tap(13) // title: Settings
  await tap(0)
  assert.equal(await run(() => __G.menus.settingsOpen), true)
  await tap(13) // mouse sensitivity
  await tap(13) // controller sensitivity
  const beforeSensitivity = await run(() => __G.menus.settings.controllerSensitivity)
  await tap(15)
  assert.ok(await run(() => __G.input.gamepad.sensitivity) > beforeSensitivity)
  await page.screenshot({ path: process.env.CONTROLLER_SCREENSHOT || '/tmp/specimen-controller-settings.png' })
  await tap(1)
  await tap(12) // title: Begin
  await button(0)
  assert.equal(await run(() => __G.mode), 'play')
  assert.equal(await run(() => document.pointerLockElement), null)
  assert.equal(await run(() => __G.player.vel.y), 0, 'menu A did not jump')
  await button(0, false)
  await tap(1)
  assert.equal(await run(() => __G.player.crouching), true)
  await tap(1)
  assert.equal(await run(() => __G.player.crouching), false)
  const old = await run(() => ({ x: __G.player.pos.x, z: __G.player.pos.z, yaw: __G.player.yaw }))
  await run(() => { testPads[0].axes = [0.3, -0.6, 0.6, 0]; __step(0.5) })
  const moved = await run(() => ({ x: __G.player.pos.x, z: __G.player.pos.z, yaw: __G.player.yaw }))
  assert.ok(Math.hypot(moved.x - old.x, moved.z - old.z) > 0.1)
  assert.notEqual(moved.yaw, old.yaw)
  await run(() => { testPads[0].axes = [0, 0, 0, 0] })
  await tap(5)
  await run(() => __step(0.5))
  assert.equal(await run(() => __G.weapons.current), 'pistol')
  const mag = await run(() => __G.weapons.mag.pistol)
  await button(7)
  await run(() => __step(0.5))
  assert.equal(await run(() => __G.weapons.mag.pistol), mag - 1, 'held trigger does not repeat single-shot fire')
  await button(7, false)
  await button(6)
  await run(() => __step(0.3))
  assert.ok(await run(() => __G.weapons.aim) > 0.5)
  await button(6, false)
  await tap(12)
  assert.equal(await run(() => __G.map.open && __G.paused), true)
  await tap(1)
  assert.equal(await run(() => __G.paused), false)
  await tap(8)
  assert.equal(await run(() => __G.journal.open && __G.paused), true)
  await tap(15)
  await tap(0)
  assert.equal(await run(() => __G.journal.tab), 'photos')
  await tap(1)
  await tap(9)
  assert.equal(await run(() => __G.paused), true)
  await tap(9)
  assert.equal(await run(() => __G.paused), false)
  // Mount through the actual interaction prompt, not a direct enter call.
  await run(() => {
    const b = __G.motorbike
    const w = b.toWorld(1.5, 0.2)
    __G.player.pos.set(w.x, __G.physics.groundAt(w.x, w.z, b.pos.y + 1), w.z)
    const target = b.board.dynamic()
    const dx = target.x - __G.player.pos.x, dz = target.z - __G.player.pos.z
    __G.player.yaw = Math.atan2(-dx, -dz)
    __G.player.pitch = Math.atan2(target.y - __G.player.pos.y - 1.63, Math.hypot(dx, dz))
    __G.player.vel.set(0, 0, 0)
  })
  await tick()
  assert.equal(await run(() => __G.interact.current?.id), 'motorbike')
  await tap(3)
  assert.equal(await run(() => __G.vehicle?.kind), 'motorbike')
  assert.equal(await run(() => __G.motorbike.driver.visible), true)
  const bikeStart = await run(() => ({ x: __G.motorbike.pos.x, z: __G.motorbike.pos.z }))
  await run(() => { testPads[0].axes = [0, -0.8, 0, 0]; __step(0.8) })
  assert.ok(await run(() => __G.motorbike.speed) > 1, 'motorbike accelerates out of its spawn')
  const bikeMoved = await run(() => ({ x: __G.motorbike.pos.x, z: __G.motorbike.pos.z }))
  assert.ok(Math.hypot(bikeMoved.x - bikeStart.x, bikeMoved.z - bikeStart.z) > 0.4)
  await tap(3)
  assert.equal(await run(() => __G.vehicle?.kind), 'motorbike', 'cannot dismount at speed')
  await run(() => { testPads[0].axes[0] = 0.65; __step(0.3) })
  assert.ok(Math.abs(await run(() => __G.motorbike.roll)) > 0.001, 'bike banks in a turn')
  assert.ok(Math.abs(await run(() => __G.motorbike.roll)) <= 0.38)
  await run(() => { testPads[0].axes = [0, 0, 0, 0] })
  await button(0)
  await run(() => __step(2))
  await button(0, false)
  assert.ok(await run(() => __G.motorbike.speed) < 1.2, 'brakes stop the bike')
  assert.ok(Math.abs(await run(() => __G.motorbike.roll)) < 0.01, 'stabilizer returns upright')
  await tap(4)
  assert.equal(await run(() => __G.motorbike.view), 'seat')
  assert.equal(await run(() => __G.motorbike.driver.visible), false)
  await tap(4)
  await tap(11)
  assert.equal(await run(() => __G.motorbike.lights), true)
  assert.match(await run(() => document.getElementById('heliHud').textContent), /STABILIZER ON/)
  await run(() => {
    const G = __G, b = G.motorbike
    const at = b.toWorld(-3.4, -3.4)
    G.camera.position.set(at.x, b.pos.y + 2.1, at.z)
    G.camera.lookAt(b.pos.x, b.pos.y + 0.9, b.pos.z)
    G.camera.updateMatrixWorld()
    G.renderer.clear()
    G.renderer.render(G.scene, G.camera)
  })
  await page.screenshot({ path: process.env.MOTORBIKE_SCREENSHOT || '/tmp/specimen-motorbike.png' })
  await tap(3)
  assert.equal(await run(() => __G.vehicle), null)
  assert.equal(await run(() => __G.motorbike.parked), true)
  await run(() => { __G.motorbike.damage(20, null, false); __G.motorbike.service() })
  assert.equal(await run(() => __G.motorbike.health), 100)
  assert.equal(await run(() => [__G.motorbike.pos.x, __G.motorbike.pos.y, __G.motorbike.pos.z, __G.motorbike.roll].every(Number.isFinite)), true)
  await run(() => __G.jeep.enter())
  await tick()
  const view = await run(() => __G.jeep.view)
  await tap(4)
  assert.notEqual(await run(() => __G.jeep.view), view)
  const lights = await run(() => __G.jeep.lights)
  await tap(11)
  assert.notEqual(await run(() => __G.jeep.lights), lights)
  await run(() => { testPads[0].axes[1] = -0.6; __step(0.5) })
  assert.ok(await run(() => __G.jeep.speed) > 0)
  await run(() => { testPads[0].axes[1] = 0; __G.jeep.exit(true); __G.heli.enter() })
  await tick()
  await button(0)
  assert.equal(await run(() => __G.input.down('ascend')), true)
  await button(0, false)
  await button(1)
  assert.equal(await run(() => __G.input.down('descend')), true)
  await button(1, false)
  await run(() => __G.heli.exit(true))
  // The submersible: board through the prompt from the moon pool's catwalk,
  // then every control on the pad.
  await run(() => {
    const G = __G
    G.player.teleport(G.island.poi.sealab.moonpool.exit.clone())
    const d = G.sub.board.dynamic(), p = G.player.pos
    G.player.yaw = Math.atan2(-(d.x - p.x), -(d.z - p.z))
    G.player.pitch = Math.atan2(d.y - (p.y + 1.63), Math.hypot(d.x - p.x, d.z - p.z))
    G.player.vel.set(0, 0, 0)
  })
  await tick()
  assert.equal(await run(() => __G.interact.current?.id), 'sub')
  await tap(3)
  assert.equal(await run(() => __G.vehicle?.kind), 'sub')
  await button(1)
  await run(() => __step(1))
  await button(1, false)
  assert.ok(await run(() => __G.sub.ballast) < -0.5, 'B floods the tanks')
  await run(() => __step(4))
  assert.ok(await run(() => __G.sub.pos.y) < -2.5, 'she dives')
  assert.equal(await run(() => __G.underwater.active), true, 'the chase camera follows her under')
  const depth = await run(() => __G.sub.pos.y)
  await run(() => __step(3))
  assert.ok(Math.abs(await run(() => __G.sub.pos.y) - depth) < 0.6, 'let go, she holds her depth')
  await run(() => { testPads[0].axes = [0, -0.8, 0, 0]; __step(2) })
  assert.ok(await run(() => __G.sub.speed) > 1, 'left stick drives the thrusters')
  await run(() => { testPads[0].axes = [0, 0, 0, 0] })
  await tap(2)
  assert.ok(await run(() => !!__G.sub.sonar), 'X pings the sonar')
  assert.match(await run(() => document.getElementById('heliHud').textContent), /SONAR/)
  await tap(11)
  assert.equal(await run(() => __G.sub.lights), true, 'right stick click: floodlights')
  await tap(4)
  assert.equal(await run(() => __G.sub.view), 'seat')
  await tap(3)
  assert.equal(await run(() => __G.vehicle?.kind), 'sub', 'no getting out under water')
  await button(0)
  await run(() => __step(8))
  await button(0, false)
  await run(() => __step(6))
  assert.equal(await run(() => __G.sub.surfaced), true, 'A blows the tanks and she surfaces')
  await tap(3)
  await tick()
  assert.equal(await run(() => __G.vehicle), null, 'Y climbs out at the surface')
  assert.equal(await run(() => __G.player.swimming), true, 'into the sea')
  await run(() => { testPads = [] })
  await tick()
  assert.equal(await run(() => __G.paused), true, 'disconnect pauses the expedition')
  assert.equal(await run(() => __G.input.down('fire')), false)
  // Keyboard still works after losing the controller.
  await page.click('#resume')
  await page.keyboard.down('KeyC')
  await tick()
  await page.keyboard.up('KeyC')
  assert.equal(await run(() => __G.player.crouching), true)
  assert.deepEqual(errors, [])
  console.log('Controller browser checks passed: menus/settings, movement/look, weapons, map/journal, pause, stabilized motorbike, jeep/helicopter, submersible, disconnect and keyboard fallback.')
} finally {
  await browser?.close()
  await server.close()
}
