# Turns the splat squirrel generator (upstream-squirrel.js: the splat-squirrel project's src/squirrel.js)
# into the Bushtail Clans' fur (bushtail.js): the squirrel's body, face, ears and tail as splats, with the
# ground and the acorn taken out, in any unit's colours (a palette), with an optional beard (the Elder's)
# and gliding membrane (the Glider's); bigger eyes; poses for the head, either arm, the legs and the tail;
# a progressive splat order whose every prefix is a coarser squirrel; and where a unit's kit goes (anchors
# on the rig, the body's surface, the leaf cloak's leaves), which is modelled as meshes, not splats
# (bushtail-kit.js).
#   python3 make-bushtail.py [upstream-squirrel.js [bushtail.js]]   (each anchor must match once)
