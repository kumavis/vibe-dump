#!/usr/bin/env node
// Bundles src/agent/page-tool.js into public/agent.js: one self-contained,
// minified ES module (CapTP, the shims, the transport) that Vite then copies
// verbatim into dist/. It cannot be a second Vite entry of the app — S3 saw a
// second entry sharing @endo make harden run before lockdown — and a file in
// public/ is served as-is, so it must have no bare imports. esbuild (Vite's own
// dependency) does the bundling. Re-run after changing the transport:
//   node agent/build-page-tool.mjs
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import { statSync } from 'node:fs'

const root = fileURLToPath(new URL('..', import.meta.url))
await build({
  absWorkingDir: root,
  entryPoints: ['src/agent/page-tool.js'],
  outfile: 'public/agent.js',
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  banner: { js: '// merge-meadow page-tool guest: generated by agent/build-page-tool.mjs from src/agent/page-tool.js. Do not edit.' },
  logLevel: 'warning',
})
console.log(`public/agent.js ${(statSync(new URL('../public/agent.js', import.meta.url)).size / 1024).toFixed(1)} KB`)
