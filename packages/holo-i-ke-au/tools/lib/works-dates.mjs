// The works, dated (DATA.md, "Works, dated: military land, airports,
// highways, rail, harbours"): one entry per feature, hand-written from the
// sources named in each, and joined to its geometry by the layer's own name
// or id (`geom`), so the bake is repeatable. RESEARCH.md §15 says what each
// kind rests on.
//
// An entry:
//   id, kind, part, group, name (the name of the day it opened), alt (later names),
//   owner, from, to (null while it stands), built ([start, end], optional),
//   datePrecision (year | decade | by), by (for "by": the sheet or record that first shows it),
//   precision (only where it is not the geometry's own: inferred),
//   width / class / storeys where the contract asks, sources (ids in sources.json), note,
//   geom: where the geometry comes from —
//     { layer, key }                     a layer's features by its key field (works-sources.mjs LAYERS): polygons merged, lines joined
//     { layer, key, within, outside }    the same, carved by hand-drawn zones (works-traced.mjs ZONES)
//     { zone, minusLand: true }          a hand-drawn zone with the land taken away: a harbour's waters
//     { runway: { airport, designator } } an FAA runway, as its centreline and published width
//     { route: { id, mp, names, island } } State DOT HPMS centrelines by route, milepost range and name
//     { enc: { harbour, scale, catslc, box } } NOAA charted shoreline construction
//     { traced }                          a shape traced from a historic sheet (works-traced.mjs TRACED)
//   tunnels (roads): [{ id, name, portals: [[lon, lat], [lon, lat]], from, ... }]
//
// Notes say what a work is and what the sources could not separate. Figures
// (acres, lengths, counts) belong in tellings, not here; years, route numbers
// and runway designators are names, not figures.
//
// Which features of the layers are taken: every feature the brief names; every
// Corps of Engineers former site whose own description (or another source)
// dates both its start and its end; and every polygon of the State's Defense
// lands layer of twenty hectares or more, dated where a source dates it and
// otherwise "by" the first sheet or record read that shows it.

