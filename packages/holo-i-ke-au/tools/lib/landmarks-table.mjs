//                                    from the OSM API, the building as mapped
//                                    today: precision exact
//   { like: 'iolani-palace', size: [L, W], along: 0.45 }
//                                    another entry's footprint: its centre and
//                                    axis, at `size` metres (L along its long
//                                    axis), or `along` times its length; for a
//                                    building gone or since altered whose
//                                    ground a source places but whose outline
//                                    no source read gives: precision inferred
//
