export const GROUP = { rim: 0, upper: 4, lower: 8, handle: 12, spout: 16, knob: 20, lid: 24, bottom: 28 }

const bern = (t, out) => {
  const m = 1 - t
  out[0] = m * m * m; out[1] = 3 * t * m * m; out[2] = 3 * t * t * m; out[3] = t * t * t
  return out
}
const dbern = (t, out) => {
  const m = 1 - t
  out[0] = -3 * m * m; out[1] = 3 * m * m - 6 * t * m; out[2] = 6 * t * m - 3 * t * t; out[3] = 3 * t * t
  return out
}
const _bs = [0, 0, 0, 0], _bt = [0, 0, 0, 0]

/**
 * A point of patch `p` at (s along the profile, t round the section), in Newell space.
 * s and t may run a little past [0, 1] (the cubic is extrapolated: handle ends sunk into the wall).
 */
export function newellPoint(p, s, t, out = [0, 0, 0]) {
  bern(s, _bs); bern(t, _bt)
  out[0] = out[1] = out[2] = 0
  for (let r = 0; r < 4; r++) {
    for (let c = 0; c < 4; c++) {
      const w = _bs[r] * _bt[c]
      const k = NEWELL_PATCHES[p * 16 + r * 4 + c] * 3
      out[0] += w * NEWELL_VERTICES[k]; out[1] += w * NEWELL_VERTICES[k + 1]; out[2] += w * NEWELL_VERTICES[k + 2]
    }
  }
  return out
}

/** Newell space → vessel space (mm, Y up, front +Z): x → X, z → Y, y → −Z, times `scale`. */
export function toVessel(q, scale, out = [0, 0, 0]) {
  out[0] = q[0] * scale; out[1] = q[2] * scale; out[2] = -q[1] * scale
  return out
}

// d/ds and d/dt are only needed by tests; kept for completeness
export function newellDerivs(p, s, t) {
  const ds = [0, 0, 0], dt = [0, 0, 0]
  const bs = bern(s, [0, 0, 0, 0]), bt = bern(t, [0, 0, 0, 0]), dbs = dbern(s, [0, 0, 0, 0]), dbt = dbern(t, [0, 0, 0, 0])
  for (let r = 0; r < 4; r++) {
    for (let c = 0; c < 4; c++) {
      const k = NEWELL_PATCHES[p * 16 + r * 4 + c] * 3
      for (let i = 0; i < 3; i++) {
        ds[i] += dbs[r] * bt[c] * NEWELL_VERTICES[k + i]
        dt[i] += bs[r] * dbt[c] * NEWELL_VERTICES[k + i]
      }
    }
  }
  return { ds, dt }
}
