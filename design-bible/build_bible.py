def pack_entry(note, n):
    ins = note.insights[n]
    key = "%s#%d" % (note.id, n)
    seg = " · stream segment" if note.is_segment else ""
    lines = [
        "### {{%s}} · w%d · %s · %s" % (key, ins["weight"], ins["kind"], norm_subtopic(ins["subtopic"])),
        "%s — \"%s\" (%s) · %s · %s%s" % (note.speaker, note.title, note.year, fmt_time(ins["t"]),
                                         caption_label(note.caption_source), seg),
        "**Claim:** %s" % ins["claim"].strip(),
        "**Detail:** %s" % ins["detail"].strip(),
        "**Quote:** \"%s\"" % ins["quote"].strip(),
    ]
    return "\n".join(lines) + "\n"


def build_pack(num, fn, topic, notes):
    items = []
    for note in notes.values():
        for n, ins in enumerate(note.insights):
            if ins["topic"] == topic:
                items.append((note, n, ins))
    groups = collections.defaultdict(list)
    for it in items:
        groups[norm_subtopic(it[2]["subtopic"])].append(it)

    def ins_sort(it):
        note, n, ins = it
        return (-ins["weight"], note.year, note.id, n)

    multi = [(sub, sorted(g, key=ins_sort)) for sub, g in groups.items() if len(g) > 1]
    multi.sort(key=lambda sg: (-sum(it[2]["weight"] for it in sg[1]), sg[0]))
    singles = sorted((g[0] for g in groups.values() if len(g) == 1),
                     key=lambda it: (-it[2]["weight"], it[0].year, norm_subtopic(it[2]["subtopic"]),
                                     it[0].id, it[1]))

    w = collections.Counter(it[2]["weight"] for it in items)
    k = collections.Counter(it[2]["kind"] for it in items)
    talks = {it[0].id for it in items}
    out = [
        "# Pack %02d — %s (working title)" % (num, chapter_title_guess(fn)),
        "",
        "Topic: `%s` · chapter source: `src/%s` · rendered: `%s`" % (topic, fn, fn),
        "",
        "%d insights from %d talks · by weight: w3 %d · w2 %d · w1 %d · by kind: %s"
        % (len(items), len(talks), w[3], w[2], w[1],
           " · ".join("%s %d" % (kk, k[kk]) for kk in KINDS if k[kk])),
        "",
        "Cite an insight by pasting its `{{key}}` (the heading's first field) directly after the "
        "statement it supports. Subtopic groups are ordered by total weight; single-insight "
        "subtopics come last.",
        "",
    ]
    for sub, g in multi:
        out.append("## %s (%d)" % (sub, len(g)))
        out.append("")
        for note, n, _ in g:
            out.append(pack_entry(note, n))
    if singles:
        out.append("## (single-insight subtopics)")
        out.append("")
        for note, n, _ in singles:
            out.append(pack_entry(note, n))
    return "\n".join(out).rstrip("\n") + "\n", len(items)


def build_talks(notes):
    by_year = collections.defaultdict(list)
    for note in notes.values():
        by_year[note.year].append(note)
    total = sum(len(n.insights) for n in notes.values())
    out = ["# Talks", "",
           "%d note files, %d insights. Ordered by year, then speaker." % (len(notes), total), ""]
    for year in sorted(by_year):
        out.append("## %s" % year)
        out.append("")
        for note in sorted(by_year[year], key=lambda n: (n.speaker.lower(), n.id)):
            dist = collections.Counter(i["topic"] for i in note.insights)
            dist_s = ", ".join("%s %d" % (t, c) for t, c in
                               sorted(dist.items(), key=lambda tc: (-tc[1], tc[0]))) or "none"
            seg = ""
            if note.is_segment:
                end = (note.d.get("segment") or {}).get("end")
                seg = " · stream segment %s–%s of video %s" % (
                    fmt_time(note.start or 0), fmt_time(end) if end is not None else "?", note.video_id)
            out.append("### %s — %s — \"%s\" (%s)" % (note.id, note.speaker, note.title, note.year))
            out.append("%s · %s%s · games: %s" % (note.d.get("talk_type", "?"),
                                                  caption_label(note.caption_source), seg,
                                                  ", ".join(note.d.get("games") or []) or "none"))
            out.append("%d insights: %s" % (len(note.insights), dist_s))
            out.append("Summary: %s" % (note.d.get("summary") or "").strip())
            out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def cmd_packs(args, notes):
    packs_dir = os.path.join(args.bible_dir, "packs")
    total = 0
    for num, fn, topic in CHAPTERS:
        if not topic:
            continue
        text, count = build_pack(num, fn, topic, notes)
        name = "%02d-%s.md" % (num, topic)
        write_file(os.path.join(packs_dir, name), text)
        total += count
        print("packs/%s: %d insights, %d words" % (name, count, len(text.split())))
    write_file(os.path.join(packs_dir, "talks.md"), build_talks(notes))
    all_ins = sum(len(n.insights) for n in notes.values())
    print("packs/talks.md: %d talks" % len(notes))
    print("total: %d insights in packs, %d in notes files" % (total, all_ins))
    if total != all_ins:
        print("ERROR: pack total does not match notes total", file=sys.stderr)
        return 1
    return 0


