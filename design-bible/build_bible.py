FENCE_RE = re.compile(r"^ {0,3}(`{3,}|~{3,})")
BQ_RE = re.compile(r"^ {0,3}>")
HEADING_RE = re.compile(r"^ {0,3}(#{1,6})\s+(.*?)\s*#*\s*$")
LIST_RE = re.compile(r"^\s*(?:[-*+]|\d+[.)])\s+")


class Doc:
    """A chapter source with code regions, tokens and line structure worked out."""

    def __init__(self, text):
        self.text = text
        self.lines = text.split("\n")
        self.line_starts = [0]
        for ln in self.lines[:-1]:
            self.line_starts.append(self.line_starts[-1] + len(ln) + 1)
        self.fenced_lines = set()
        self.code_spans = []  # (start, end) char offsets
        self.unclosed_fence = None
        self._find_code()
        starts = [s for s, _ in self.code_spans]
        self._code_starts = starts
        self.tokens = []  # dicts: start, end, content, line
        for m in TOKEN_RE.finditer(text):
            if not self.in_code(m.start()):
                self.tokens.append({"start": m.start(), "end": m.end(), "content": m.group(1),
                                    "line": self.line_of(m.start())})

    def _find_code(self):
        open_fence = None
        block_start = None
        prose_chunks = []  # (start, end) of non-fenced text runs
        chunk_start = 0
        for i, ln in enumerate(self.lines):
            m = FENCE_RE.match(ln)
            if open_fence is None:
                if m:
                    open_fence = (m.group(1)[0], len(m.group(1)), i)
                    block_start = self.line_starts[i]
                    prose_chunks.append((chunk_start, block_start))
                    self.fenced_lines.add(i)
            else:
                self.fenced_lines.add(i)
                if (m and m.group(1)[0] == open_fence[0] and len(m.group(1)) >= open_fence[1]
                        and ln.strip().strip(open_fence[0]) == ""):
                    end = self.line_starts[i] + len(ln)
                    self.code_spans.append((block_start, end))
                    chunk_start = end
                    open_fence = None
        if open_fence is not None:
            self.unclosed_fence = open_fence[2] + 1
            self.code_spans.append((block_start, len(self.text)))
        else:
            prose_chunks.append((chunk_start, len(self.text)))
        # inline code spans inside prose chunks (may cross lines, like CommonMark)
        for cs, ce in prose_chunks:
            chunk = self.text[cs:ce]
            runs = [(m.start(), m.end()) for m in re.finditer(r"`+", chunk)]
            i = 0
            while i < len(runs):
                s, e = runs[i]
                n = e - s
                j = i + 1
                while j < len(runs) and runs[j][1] - runs[j][0] != n:
                    j += 1
                if j < len(runs):
                    seg = chunk[s:runs[j][1]]
                    if "\n\n" not in seg and not re.search(r"\n\s*\n", seg):
                        self.code_spans.append((cs + s, cs + runs[j][1]))
                        i = j + 1
                        continue
                i += 1
        self.code_spans.sort()

    def in_code(self, pos):
        i = bisect.bisect_right(self._code_starts, pos) - 1
        return i >= 0 and self.code_spans[i][0] <= pos < self.code_spans[i][1]

    def line_of(self, pos):
        return bisect.bisect_right(self.line_starts, pos)

    def headings(self):
        out = []
        for i, ln in enumerate(self.lines):
            if i in self.fenced_lines:
                continue
            m = HEADING_RE.match(ln)
            if m:
                out.append((i + 1, len(m.group(1)), m.group(2).strip()))
        return out


def key_problem(content, notes):
    """Return (note, n, None) for a good key, else (None, None, message)."""
    if content != content.strip():
        return None, None, "malformed key {{%s}}: remove the spaces inside the braces" % content
    m = KEY_RE.match(content)
    if not m:
        hint = ""
        if "#" not in content:
            hint = " (missing '#<n>' insight index)"
        return None, None, ("malformed key {{%s}}: expected {{<note-id>#<n>}}, e.g. {{lfb6uehmrWo#4}}%s"
                            % (content, hint))
    nid, n = m.group("id"), int(m.group("n"))
    note = notes.get(nid)
    if note is None:
        ids = sorted(notes)
        sugg = [i for i in ids if i.lower() == nid.lower()]
        if "@" in nid:
            sugg += [i for i in ids if i.startswith(nid.split("@")[0] + "@")]
        sugg += difflib.get_close_matches(nid, ids, n=3, cutoff=0.6)
        sugg = list(dict.fromkeys(s for s in sugg if s != nid))[:4]
        msg = "unknown note id %r in {{%s}}" % (nid, content)
        msg += (" — did you mean: %s?" % ", ".join(sugg)) if sugg else " — no similar note id found"
        return None, None, msg
    if n >= len(note.insights):
        cnt = len(note.insights)
        rng = ("valid: #0–#%d" % (cnt - 1)) if cnt else "it has no insights"
        return None, None, ("insight index out of range in {{%s}}: note %s has %d insight(s) (%s)"
                            % (content, nid, cnt, rng))
    return note, n, None


def blockquotes(doc):
    """Groups of consecutive blockquote lines (0-based line indexes) outside code."""
    groups, cur = [], []
    for i, ln in enumerate(doc.lines):
        if i not in doc.fenced_lines and BQ_RE.match(ln):
            cur.append(i)
        else:
            if cur:
                groups.append(cur)
            cur = []
    if cur:
        groups.append(cur)
    return groups


def analyse(name, text, notes):
    """Parse a chapter source. Returns dict with doc, errors, warnings, citations, runs."""
    doc = Doc(text)
    errors, warnings = [], []

    def err(line, msg):
        errors.append((line, msg))

    if doc.unclosed_fence:
        err(doc.unclosed_fence, "code fence opened here is never closed (everything after it is "
                                "treated as code, so its keys would not render)")

    # Keys
    cites = []  # (line, note, n)
    for tok in doc.tokens:
        note, n, problem = key_problem(tok["content"], notes)
        tok["note"], tok["n"] = note, n
        if problem:
            err(tok["line"], problem)
        else:
            cites.append((tok["line"], note, n))

    # Stray braces / single-brace or bare keys outside code and outside tokens
    tok_spans = [(t["start"], t["end"]) for t in doc.tokens]

    def in_token(pos):
        return any(s <= pos < e for s, e in tok_spans)

    for m in re.finditer(r"\{\{|\}\}", text):
        if not doc.in_code(m.start()) and not in_token(m.start()):
            ln = doc.line_of(m.start())
            snippet = doc.lines[ln - 1].strip()
            err(ln, "malformed key: unmatched %r (a key must be {{<note-id>#<n>}} on one line): %s"
                % (m.group(0), snippet[:80]))
    for m in re.finditer(r"(?<![{\w@/#-])\{?([A-Za-z0-9_-]+(?:@\d+)?#\d+)\}?(?![}\w])", text):
        if doc.in_code(m.start()) or in_token(m.start()):
            continue
        if m.group(1).split("#")[0] in notes:
            err(doc.line_of(m.start()), "malformed key %r: wrap insight keys in double braces, "
                                        "{{%s}}" % (m.group(0), m.group(1)))

    # Hand-written YouTube links
    for m in YOUTUBE_RE.finditer(text):
        if not doc.in_code(m.start()):
            err(doc.line_of(m.start()), "hand-written YouTube link (%s...): cite with an insight key "
                                        "instead; render makes the link" % m.group(0))

    # Runs of keys
    runs = []
    for tok in doc.tokens:
        if runs:
            prev = runs[-1][-1]
            gap = text[prev["end"]:tok["start"]]
            if gap.strip() == "" and not re.search(r"\n\s*\n", gap):
                runs[-1].append(tok)
                continue
        runs.append([tok])

    # Blockquotes
    bq_line_set = {}
    for g in blockquotes(doc):
        first, last = g[0], g[-1]
        span_s = doc.line_starts[first]
        span_e = doc.line_starts[last] + len(doc.lines[last])
        toks = [t for t in doc.tokens if span_s <= t["start"] < span_e]
        for i in g:
            bq_line_set[i] = g
        if not toks:
            err(first + 1, "blockquote with no key: pull quotes must end with the {{key}} of the "
                           "insight whose quote they use")
            continue
        if len(toks) > 1:
            err(first + 1, "blockquote with %d keys: a pull quote cites exactly one insight"
                % len(toks))
            continue
        tok = toks[0]
        if tok["note"] is None:
            continue
        body = text[span_s:span_e]
        rel_s, rel_e = tok["start"] - span_s, tok["end"] - span_s
        body = body[:rel_s] + " " + body[rel_e:]
        body = "\n".join(re.sub(r"^ {0,3}>\s?", "", ln) for ln in body.split("\n"))
        nq = norm_quote(body)
        quote = tok["note"].insights[tok["n"]]["quote"]
        nquote = norm_quote(quote)
        if not nq:
            err(first + 1, "blockquote has no quoted text")
        elif (" %s " % nq) not in (" %s " % nquote):
            err(first + 1, "blockquote text is not in the quote of {{%s#%d}}; you may only fix "
                           "capitalisation/punctuation and trim from either end.\n"
                           "      your text:     %s\n      insight quote: \"%s\""
                % (tok["note"].id, tok["n"], " ".join(body.split()), quote))
        tok["bq"] = True

    return {"doc": doc, "errors": sorted(errors, key=lambda e: e[0]), "warnings": warnings,
            "cites": cites, "runs": runs}


def render_text(name, text, a):
    out = []
    pos = 0

    def tail():
        return out[-1][-1:] if out and out[-1] else ""

    for run in a["runs"]:
        seg = text[pos:run[0]["start"]]
        if any(t.get("bq") for t in run):
            seg = re.sub(r"[ \t]*(?:[—–]|--?)?[ \t]*$", "", seg)
            out.append(seg)
            sep = "" if tail() in ("", "\n") else " "
            out.append(sep + "— " + ", ".join(link_for(t["note"], t["n"]) for t in run))
        else:
            seg = re.sub(r"[ \t]+$", "", seg)
            out.append(seg)
            sep = "" if tail() in ("", "\n") else " "
            out.append(sep + "(" + "; ".join(link_for(t["note"], t["n"]) for t in run) + ")")
        pos = run[-1]["end"]
    out.append(text[pos:])
    body = "".join(out)
    return GENERATED_NOTE.format(name=name) + "\n" + body


