def fmt_time(t):
    t = int(t)
    h, rem = divmod(t, 3600)
    m, s = divmod(rem, 60)
    if h:
        return "%d:%02d:%02d" % (h, m, s)
    return "%d:%02d" % (m, s)


def speaker_short(speaker):
    s = re.sub(r"\([^)]*\)", " ", speaker)
    parts = [p.strip() for p in re.split(r"\s*(?:,|;|&|\band\b)\s*", s)]
    parts = [p for p in parts if p]
    if not parts:
        return speaker.strip()
    if len(parts) > 2:
        return parts[0] + " et al."
    return " and ".join(parts)


def md_escape(s):
    return s.replace("[", "\\[").replace("]", "\\]")


def link_for(note, n):
    ins = note.insights[n]
    text = "%s %s, %s" % (speaker_short(note.speaker), note.year, fmt_time(ins["t"]))
    return "[%s](https://youtu.be/%s?t=%d)" % (md_escape(text), note.video_id, int(ins["t"]))


def caption_label(src):
    return "%s captions" % src if src else "captions unknown"


def norm_subtopic(s):
    return " ".join(s.lower().split())


def norm_quote(s):
    s = unicodedata.normalize("NFKC", s).lower()
    return " ".join(re.sub(r"[\W_]+", " ", s).split())


def write_file(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def chapter_title_guess(fn):
    words = fn[3:-3].replace("-", " ")
    return words[:1].upper() + words[1:]


