def src_files(bible_dir, which):
    src_dir = os.path.join(bible_dir, "src")
    files = sorted(glob.glob(os.path.join(src_dir, "[0-9][0-9]-*.md")))
    problems = []
    if which:
        wanted = []
        for w in which:
            if not w.isdigit():
                problems.append("chapter %r: give chapter numbers like 3 or 03" % w)
                continue
            n = int(w)
            hits = [f for f in files if int(os.path.basename(f)[:2]) == n]
            if not hits:
                problems.append("chapter %02d: no src/%02d-*.md in %s" % (n, n, src_dir))
            wanted += hits
        files = list(dict.fromkeys(wanted))
    return files, problems


