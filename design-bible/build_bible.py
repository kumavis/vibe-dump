def cmd_cited(args, notes):
    if len(args.chapters) != 1:
        raise FatalError("cited takes exactly one chapter number, e.g. cited 03")
    num = parse_chapter_num(args.chapters[0])
    files, problems = src_files(args.bible_dir, [str(num)])
    if problems:
        raise FatalError(problems[0])
    if len(files) > 1:
        raise FatalError("more than one src/%02d-*.md: %s" % (num, ", ".join(map(os.path.basename, files))))
    path = files[0]
    name = os.path.basename(path)
    a = analyse(name, read(path), notes)
    key_errs = [e for e in a["errors"]
                if e[1].startswith(("malformed key", "unknown note id", "insight index"))]
    if key_errs:
        print("src/%s: %d key error(s), nothing written" % (name, len(key_errs)))
        print_errors(name, key_errs)
        return 1
    lines_of = collections.OrderedDict()
    for line, note, n in a["cites"]:
        lines_of.setdefault((note.id, n), (note, []))[1].append(line)
    root = os.path.dirname(HERE)
    tdir = os.path.abspath(args.transcripts_dir)
    out = ["# Cited insights — src/%s" % name, "",
           "%d citations of %d distinct insights, in order of first appearance. Each entry gives the "
           "insight in full, where it sits in its note and transcript, and the chapter lines that "
           "cite it." % (len(a["cites"]), len(lines_of)), ""]
    for (nid, n), (note, lines) in lines_of.items():
        ins = note.insights[n]
        tpath = os.path.join(tdir, note.video_id + ".txt")
        trel = os.path.relpath(tpath, root)
        missing = "" if os.path.exists(tpath) else " (file not found)"
        out.append(pack_entry(note, n).rstrip("\n"))
        out.append("**Source:** note `%s` insight #%d · topic %s · t=%d s (%s) · transcript `%s`%s"
                   % (note.id, n, ins["topic"], int(ins["t"]), fmt_time(ins["t"]), trel, missing))
        out.append("**Cited at lines:** %s" % ", ".join(map(str, lines)))
        out.append("")
    dest = os.path.join(args.bible_dir, "packs", "cited", "%02d.md" % num)
    write_file(dest, "\n".join(out).rstrip("\n") + "\n")
    print("packs/cited/%02d.md: %d citations, %d distinct insights" % (num, len(a["cites"]), len(lines_of)))
    other = [e for e in a["errors"] if e not in key_errs]
    if other:
        print("  note: src/%s has %d other render error(s); run check %02d" % (name, len(other), num))
    return 0


