def cmd_partpack(args, notes):
    if len(args.chapters) != 1:
        raise FatalError("partpack takes exactly one chapter number, e.g. partpack 03")
    num = parse_chapter_num(args.chapters[0])
    outline, errors, warnings, info = load_outline(args.bible_dir, num, notes)
    print("outlines/%02d.json: %d error(s), %d warning(s)" % (num, len(errors), len(warnings)))
    print_outline_problems(errors, warnings)
    if errors:
        print("nothing written")
        return 1
    pdir = os.path.join(args.bible_dir, "packs", "parts")
    for old in sorted(glob.glob(os.path.join(pdir, "%02d-part*.md" % num))):
        os.remove(old)
    for part in outline["parts"]:
        text = build_part_pack(outline, part)
        name = "%02d-part%d.md" % (num, part)
        write_file(os.path.join(pdir, name), text)
        mine = [s for s in outline["sections"] if s["part"] == part]
        keys = [k for s in mine for k in s["keys"]]
        print("packs/parts/%s: %d section%s, %d insights (%s), %d words"
              % (name, len(mine), "" if len(mine) == 1 else "s", len(keys), weight_counts(keys),
                 len(text.split())))
    return 0


def section_spans(doc):
    """[(heading, first_line, end_line_exclusive)] for each ## heading (1-based lines)."""
    heads = [h for h in doc.headings() if h[1] <= 2]
    spans = []
    for i, (ln, lvl, title) in enumerate(heads):
        if lvl != 2:
            continue
        end = heads[i + 1][0] if i + 1 < len(heads) else len(doc.lines) + 1
        spans.append((title, ln, end))
    return spans


def cov_dict(pairs, cited):
    out = {}
    for w in (3, 2, 1):
        ks = {(note.id, n) for note, n in pairs if note.insights[n]["weight"] == w}
        out["w%d" % w] = {"cited": len(ks & cited), "total": len(ks)}
    return out


def cov_str(c):
    return "  ".join("%s %d/%d" % (w, c[w]["cited"], c[w]["total"]) for w in ("w3", "w2", "w1"))


def part_report(args, notes, num, part):
    name = "%02d-part%d.md" % (num, part)
    rel = "src/parts/" + name
    rep = {"part_file": rel, "chapter": num, "part": part, "errors": [], "warnings": []}
    outline, oerrors, _, _ = load_outline(args.bible_dir, num, notes)
    if oerrors:
        rep["errors"] = [{"line": 0, "message": "outline: " + e} for e in oerrors]
        return rep
    if part not in outline["parts"]:
        rep["errors"] = [{"line": 0, "message": "outlines/%02d.json has no part %d (parts: %s)"
                          % (num, part, ", ".join(map(str, outline["parts"])))}]
        return rep
    path = os.path.join(args.bible_dir, "src", "parts", name)
    if not os.path.exists(path):
        rep["errors"] = [{"line": 0, "message": "%s not found" % path}]
        return rep
    text = read(path)
    a = analyse(name, text, notes)
    doc = a["doc"]
    errors = list(a["errors"])
    mine = [s for s in outline["sections"] if s["part"] == part]

    # headings
    expected = [s["heading"] for s in mine]
    heads = doc.headings()
    for ln, lvl, title in heads:
        if lvl == 1:
            errors.append((ln, "part files have no chapter title: remove '# %s'" % title))
    found = [(ln, title) for ln, lvl, title in heads if lvl == 2]
    if [t for _, t in found] != expected:
        msg = ["'## ' headings must be exactly the outline's part-%d sections, in order:" % part]
        msg += ["      expected: " + (" | ".join(expected) or "(none)"),
                "      found:    " + (" | ".join("%s (line %d)" % (t, ln) for ln, t in found) or "(none)")]
        bad_at = next((ln for i, (ln, t) in enumerate(found)
                       if i >= len(expected) or t != expected[i]), found[-1][0] if found else 0)
        errors.append((bad_at, "\n".join(msg)))
    first_h2 = found[0][0] if found else len(doc.lines) + 1

    cited = collections.OrderedDict()
    for _, note, n in a["cites"]:
        cited[(note.id, n)] = note
    cited_set = set(cited)
    assigned = [k for s in mine for k in s["keys"]]
    assigned_set = {(note.id, n) for note, n in assigned}
    prose = "\n".join(ln for i, ln in enumerate(doc.lines) if i not in doc.fenced_lines)
    rep.update({
        "words": len(prose_words(prose)), "citations": len(a["cites"]),
        "distinct_insights": len(cited), "distinct_talks": len({k[0] for k in cited}),
        "coverage": cov_dict(assigned, cited_set)})

    def entry(note, n, extra=None):
        ins = note.insights[n]
        e = {"key": "%s#%d" % (note.id, n), "subtopic": norm_subtopic(ins["subtopic"]),
             "claim": ins["claim"][:80]}
        if extra:
            e.update(extra)
        return e

    rep["uncited_w3"] = [entry(nt, n) for nt, n in assigned
                         if nt.insights[n]["weight"] == 3 and (nt.id, n) not in cited_set]
    rep["uncited_w2"] = [entry(nt, n) for nt, n in assigned
                         if nt.insights[n]["weight"] == 2 and (nt.id, n) not in cited_set]

    # per section (by outline heading; text matched to the ## heading of the same name)
    spans = {norm_heading(t): (s, e) for t, s, e in section_spans(doc)}
    secs = []
    for s in mine:
        span = spans.get(norm_heading(s["heading"]))
        words = 0
        if span:
            seg = "\n".join(ln for i, ln in enumerate(doc.lines)
                            if span[0] <= i + 1 < span[1] and i not in doc.fenced_lines)
            words = len(prose_words(seg))
        secs.append({"heading": s["heading"], "present": bool(span), "words": words,
                     "coverage": cov_dict(s["keys"], cited_set)})
    rep["sections"] = secs

    # cited keys not assigned to this part
    owner = {}
    for s in outline["sections"]:
        for note, n in s["keys"]:
            owner[(note.id, n)] = s
    omitted = {(note.id, n) for note, n, _ in outline["omitted"]}
    extra = [k for k in cited if k not in assigned_set]
    rep["unassigned_cited"] = len(extra)
    rep["cited_from_other_parts"] = [
        entry(cited[k], k[1], {"part": owner[k]["part"], "section": owner[k]["heading"]})
        for k in extra if k in owner]
    rep["cited_omitted"] = [entry(cited[k], k[1]) for k in extra if k in omitted]

    warnings = uncited_prose(doc, [])
    rep["errors"] = [{"line": l, "message": m} for l, m in sorted(errors, key=lambda e: e[0])]
    rep["warnings"] = [{"line": l, "message": m} for l, m in sorted(warnings, key=lambda e: e[0])]
    rep["preamble_lines"] = first_h2 - 1
    return rep


def cmd_check_part(args, notes):
    num = parse_chapter_num(args.part[0])
    if not args.part[1].isdigit():
        raise FatalError("part %r: give a part number like 1" % args.part[1])
    r = part_report(args, notes, num, int(args.part[1]))
    failed = bool(r["errors"])
    if args.json:
        json.dump(r, sys.stdout, indent=2, ensure_ascii=False)
        sys.stdout.write("\n")
        return 1 if failed else 0
    print("== %s" % r["part_file"])
    if "words" in r:
        print("  words %d · citations %d · distinct insights %d · distinct talks %d"
              % (r["words"], r["citations"], r["distinct_insights"], r["distinct_talks"]))
        print("  coverage of assigned keys: " + cov_str(r["coverage"]))
        for lbl, lst in (("weight-3", r["uncited_w3"]), ("weight-2", r["uncited_w2"])):
            if lst:
                print("  uncited assigned %s keys (%d):" % (lbl, len(lst)))
                for u in lst:
                    print("    {{%s}}  [%s]  %s" % (u["key"], u["subtopic"], u["claim"]))
        print("  sections:")
        for s in r["sections"]:
            print("    %-40s %5d words   %s%s" % (s["heading"][:40], s["words"], cov_str(s["coverage"]),
                                               "" if s["present"] else "   (heading not found)"))
        print("  cited keys not assigned to this part: %d" % r["unassigned_cited"])
        for u in r["cited_from_other_parts"]:
            print("    {{%s}}  assigned to part %d, \"%s\" — possible duplication: %s"
                  % (u["key"], u["part"], u["section"], u["claim"]))
        for u in r["cited_omitted"]:
            print("    {{%s}}  listed in the outline's \"omitted\": %s" % (u["key"], u["claim"]))
    print_warnings_errors(r["warnings"], r["errors"], r["part_file"])
    print("  => %d error(s), %d warning(s)" % (len(r["errors"]), len(r["warnings"])))
    return 1 if failed else 0


