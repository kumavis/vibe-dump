def cmd_sources(args, notes):
    files, _ = src_files(args.bible_dir, None)
    cited_in = collections.defaultdict(set)   # note id -> chapter filenames
    cited_keys = set()
    for path in files:
        name = os.path.basename(path)
        doc = Doc(read(path))
        for tok in doc.tokens:
            note, n, problem = key_problem(tok["content"], notes)
            if note is not None:
                cited_in[note.id].add(name)
                cited_keys.add((note.id, n))
    by_year = collections.defaultdict(list)
    for note in notes.values():
        by_year[note.year].append(note)
    out = ["<!-- GENERATED by build_bible.py from the notes and src/*.md -- do not edit this "
           "file; run `python3 build_bible.py sources`. -->",
           "# Sources", "",
           "Every Roguelike Celebration talk the bible draws on, newest first. Each title opens the "
           "talk on YouTube (talks that only exist inside a full-day stream recording open at the "
           "talk's start). \"Cited in\" lists the chapters that cite the talk; the citations inside "
           "the chapters open the video at the exact moment.", ""]
    never = []
    for year in sorted(by_year, reverse=True):
        out.append("## %s" % year)
        out.append("")
        for note in sorted(by_year[year], key=lambda n: (n.speaker.lower(), n.title.lower(), n.id)):
            chs = sorted(cited_in.get(note.id, ()))
            if chs:
                where = "cited in " + ", ".join("[%s](%s)" % (c[:2], c) for c in chs)
            else:
                where = "not cited"
                never.append(note)
            out.append("- %s — [%s](%s) · %s · %d insight%s · %s" % (
                note.speaker, md_escape(note.title), note.video_url,
                caption_label(note.caption_source), len(note.insights),
                "" if len(note.insights) == 1 else "s", where))
        out.append("")
    total = sum(len(n.insights) for n in notes.values())
    out += ["## Totals", "",
            "- Talks: %d" % len(notes),
            "- Insights: %d" % total,
            "- Insights cited at least once: %d" % len(cited_keys),
            "- Talks never cited: %d" % len(never)]
    for note in sorted(never, key=lambda n: (-n.year, n.speaker.lower(), n.id)):
        out.append("  - %s — [%s](%s) (%s)" % (note.speaker, md_escape(note.title), note.video_url,
                                              note.year))
    write_file(os.path.join(args.bible_dir, "sources.md"), "\n".join(out).rstrip("\n") + "\n")
    print("sources.md: %d talks, %d insights, %d cited, %d talks never cited"
          % (len(notes), total, len(cited_keys), len(never)))
    return 0


