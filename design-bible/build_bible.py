PART_MAX_INSIGHTS = 140
PART_MIN_INSIGHTS = 25
SECTION_MAX_INSIGHTS = 45
OMIT_W2_MAX_FRACTION = 0.15


def norm_heading(s):
    return " ".join(s.split()).lower()


def load_outline(bible_dir, num, notes):
    """Validate outlines/NN.json. Returns (outline or None, errors, warnings, info).
    outline = {"chapter", "title", "thesis", "sections": [{part, heading, brief,
    keys: [(note, n)]}], "omitted": [(note, n, reason)], "parts": [1..P]}."""
    rel = "outlines/%02d.json" % num
    path = os.path.join(bible_dir, rel)
    errors, warnings = [], []
    if num not in CHAPTER_BY_NUM or not CHAPTER_BY_NUM[num][1]:
        return None, ["chapter %02d has no topic pack; outlines are for chapters 01-18" % num], [], {}
    topic = CHAPTER_BY_NUM[num][1]
    try:
        with open(path, encoding="utf-8") as f:
            raw = f.read()
    except OSError:
        return None, ["%s not found" % path], [], {}
    try:
        d = json.loads(raw)
    except ValueError as e:
        return None, ["%s: invalid JSON: %s" % (rel, e)], [], {}
    if not isinstance(d, dict):
        return None, ["%s: top level must be a JSON object" % rel], [], {}

    def typed(obj, field, typ, where, nonempty=False):
        if field not in obj:
            errors.append("%s: missing field \"%s\"" % (where, field))
            return None
        v = obj[field]
        if not isinstance(v, typ) or isinstance(v, bool):
            tname = {int: "an integer", str: "a string", list: "a list"}[typ]
            errors.append("%s: \"%s\" must be %s, got %s" % (where, field, tname, json.dumps(v)[:60]))
            return None
        if nonempty and (not v.strip() if isinstance(v, str) else not v):
            errors.append("%s: \"%s\" is empty" % (where, field))
            return None
        return v

    chapter = typed(d, "chapter", int, rel)
    title = typed(d, "title", str, rel, nonempty=True)
    thesis = typed(d, "thesis", str, rel, nonempty=True)
    sections_raw = typed(d, "sections", list, rel, nonempty=True)
    omitted_raw = typed(d, "omitted", list, rel)
    if chapter is not None and chapter != num:
        errors.append("%s: \"chapter\" is %d but this is the outline for chapter %d" % (rel, chapter, num))

    where_key = {}  # (id, n) -> list of places
    sections = []
    for i, sec in enumerate(sections_raw or []):
        w = "%s: sections[%d]" % (rel, i)
        if not isinstance(sec, dict):
            errors.append("%s must be an object" % w)
            continue
        part = typed(sec, "part", int, w)
        heading = typed(sec, "heading", str, w, nonempty=True)
        if heading:
            w = "%s (\"%s\")" % (w, heading)
        brief = typed(sec, "brief", str, w, nonempty=True)
        keys = typed(sec, "keys", list, w)
        if part is not None and part < 1:
            errors.append("%s: \"part\" must be 1 or more, got %d" % (w, part))
        good = []
        if keys is not None and not keys:
            errors.append("%s: section has no keys" % w)
        for j, k in enumerate(keys or []):
            if not isinstance(k, str):
                errors.append("%s: keys[%d] must be a string like \"lfb6uehmrWo#4\"" % (w, j))
                continue
            note, n, problem = key_problem(k, notes)
            if problem:
                errors.append("%s: keys[%d]: %s" % (w, j, problem))
                continue
            good.append((note, n))
            where_key.setdefault((note.id, n), []).append("section \"%s\"" % (heading or i))
        sections.append({"part": part, "heading": heading, "brief": brief, "keys": good, "index": i})

    omitted = []
    for i, om in enumerate(omitted_raw or []):
        w = "%s: omitted[%d]" % (rel, i)
        if not isinstance(om, dict):
            errors.append("%s must be an object {\"key\": ..., \"reason\": ...}" % w)
            continue
        k = typed(om, "key", str, w)
        reason = typed(om, "reason", str, w)
        if reason is not None and not reason.strip():
            errors.append("%s (%s): empty reason" % (w, k))
        if k is None:
            continue
        note, n, problem = key_problem(k, notes)
        if problem:
            errors.append("%s: %s" % (w, problem))
            continue
        omitted.append((note, n, reason or ""))
        where_key.setdefault((note.id, n), []).append("omitted")

    for (nid, n), places in sorted(where_key.items()):
        if len(places) > 1:
            errors.append("%s: key %s#%d is listed more than once: %s" % (rel, nid, n, ", ".join(places)))

    # every insight of the topic must be placed or omitted
    missing = []
    for nid in sorted(notes):
        note = notes[nid]
        for n, ins in enumerate(note.insights):
            if ins["topic"] == topic and (nid, n) not in where_key:
                missing.append((ins["weight"], nid, n, ins))
    missing.sort(key=lambda m: (-m[0], norm_subtopic(m[3]["subtopic"]), m[1], m[2]))
    for wgt, nid, n, ins in missing:
        errors.append("%s: %s insight %s#%d (w%d, %s) is in neither a section nor \"omitted\": %s"
                      % (rel, topic, nid, n, wgt, norm_subtopic(ins["subtopic"]), ins["claim"][:80]))

    # part numbering and contiguity
    seq = [s["part"] for s in sections if s["part"] is not None]
    parts = sorted(set(seq))
    if parts and parts != list(range(1, len(parts) + 1)):
        errors.append("%s: parts must be numbered 1..P with none skipped; found %s"
                      % (rel, ", ".join(map(str, parts))))
    order = []
    for p in seq:
        if not order or order[-1] != p:
            order.append(p)
    if len(order) != len(set(order)):
        errors.append("%s: the sections of each part must be contiguous in \"sections\"; part order "
                      "found: %s" % (rel, " ".join(map(str, order))))
    elif order != sorted(order):
        errors.append("%s: parts must appear in order (1 before 2 ...); found %s"
                      % (rel, " ".join(map(str, order))))

    seen_h = {}
    for s in sections:
        if s["heading"]:
            h = norm_heading(s["heading"])
            if h in seen_h:
                errors.append("%s: duplicate section heading \"%s\" (sections[%d] and sections[%d])"
                              % (rel, s["heading"], seen_h[h], s["index"]))
            else:
                seen_h[h] = s["index"]

    # warnings
    info = {"other_topic_keys": 0}
    multi = len(parts) > 1
    for p in parts:
        cnt = sum(len(s["keys"]) for s in sections if s["part"] == p)
        if cnt > PART_MAX_INSIGHTS:
            warnings.append("part %d has %d insights (more than %d)" % (p, cnt, PART_MAX_INSIGHTS))
        if multi and cnt < PART_MIN_INSIGHTS:
            warnings.append("part %d has only %d insights (fewer than %d)" % (p, cnt, PART_MIN_INSIGHTS))
    for s in sections:
        if len(s["keys"]) > SECTION_MAX_INSIGHTS:
            warnings.append("section \"%s\" has %d insights (more than %d)"
                            % (s["heading"], len(s["keys"]), SECTION_MAX_INSIGHTS))
    for note, n, reason in omitted:
        ins = note.insights[n]
        if ins["weight"] == 3:
            warnings.append("weight-3 key %s#%d is omitted (%s): %s"
                            % (note.id, n, reason.strip() or "no reason", ins["claim"][:80]))
    w2_total = sum(1 for nt in notes.values() for i in nt.insights
                   if i["topic"] == topic and i["weight"] == 2)
    w2_om = sum(1 for note, n, _ in omitted
                if note.insights[n]["topic"] == topic and note.insights[n]["weight"] == 2)
    if w2_total and w2_om > OMIT_W2_MAX_FRACTION * w2_total:
        warnings.append("%d of %d weight-2 %s keys omitted (%d%%, more than %d%%)"
                        % (w2_om, w2_total, topic, round(100.0 * w2_om / w2_total),
                           round(100 * OMIT_W2_MAX_FRACTION)))
    other = sum(1 for s in sections for note, n in s["keys"] if note.insights[n]["topic"] != topic)
    info["other_topic_keys"] = other
    if other:
        warnings.append("%d key(s) from other topics assigned to sections (allowed)" % other)

    outline = {"chapter": num, "title": title, "thesis": thesis, "sections": sections,
               "omitted": omitted, "parts": parts, "topic": topic}
    return outline, errors, warnings, info


def weight_counts(pairs):
    c = collections.Counter(note.insights[n]["weight"] for note, n in pairs)
    return "w3 %d · w2 %d · w1 %d" % (c[3], c[2], c[1])


def build_part_pack(outline, part):
    num, title = outline["chapter"], outline["title"]
    nparts = len(outline["parts"])
    mine = [s for s in outline["sections"] if s["part"] == part]
    keys = [k for s in mine for k in s["keys"]]
    other = sum(1 for note, n in keys if note.insights[n]["topic"] != outline["topic"])
    out = [
        "# Part pack %02d · part %d of %d — %s" % (num, part, nparts, title),
        "",
        "Chapter %02d: %s · topic `%s` · outline `outlines/%02d.json` · write `src/parts/%02d-part%d.md`"
        % (num, title, outline["topic"], num, num, part),
        "",
        "**Thesis:** %s" % outline["thesis"].strip(),
        "",
        "This part: %d section%s, %d insights (%s; %d from other topics)."
        % (len(mine), "" if len(mine) == 1 else "s", len(keys), weight_counts(keys), other),
        "",
        "Your file must contain exactly these `## ` headings, in this order, and nothing above "
        "the first one (no chapter title, no \"In brief\"); `###` subsections are up to you:",
        "",
    ]
    out += ["    ## %s" % s["heading"] for s in mine]
    out += ["", "## Chapter outline (all parts)", ""]
    for s in outline["sections"]:
        line = "Part %d · %s — %s" % (s["part"], s["heading"], " ".join(s["brief"].split()))
        if s["part"] == part:
            out.append("- **%s** ← THIS PART" % line)
        else:
            out.append("- %s" % line)
    out.append("")
    for s in mine:
        out += ["## %s" % s["heading"], "",
                "*Brief:* %s" % s["brief"].strip(), "",
                "%d insights (%s)." % (len(s["keys"]), weight_counts(s["keys"])), ""]
        for note, n in s["keys"]:
            out.append(pack_entry(note, n))
    return "\n".join(out).rstrip("\n") + "\n"


