def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("command", choices=["packs", "render", "check", "sources", "all",
                                        "partpack", "cited"])
    p.add_argument("chapters", nargs="*", help="chapter numbers (render/check/partpack/cited)")
    p.add_argument("--part", nargs=2, metavar=("NN", "K"),
                   help="check: check src/parts/NN-partK.md against outlines/NN.json")
    p.add_argument("--notes-dir", default=DEFAULT_NOTES_DIR)
    p.add_argument("--transcripts-dir", default=DEFAULT_TRANSCRIPTS_DIR)
    p.add_argument("--bible-dir", default=HERE)
    p.add_argument("--json", action="store_true", help="check: emit JSON on stdout")
    args = p.parse_args(argv)
    if args.chapters and args.command not in ("render", "check", "partpack", "cited"):
        p.error("chapter numbers only apply to render, check, partpack and cited")
    if args.part and (args.command != "check" or args.chapters):
        p.error("--part NN K is used as: check --part NN K")
    if args.json and args.command != "check":
        p.error("--json only applies to check")
    args.bible_dir = os.path.abspath(args.bible_dir)
    try:
        notes = load_notes(os.path.abspath(args.notes_dir), os.path.abspath(args.transcripts_dir))
        if args.command == "packs":
            return cmd_packs(args, notes)
        if args.command == "render":
            return cmd_render(args, notes)
        if args.command == "check":
            return cmd_check_part(args, notes) if args.part else cmd_check(args, notes)
        if args.command == "partpack":
            return cmd_partpack(args, notes)
        if args.command == "cited":
            return cmd_cited(args, notes)
        if args.command == "sources":
            return cmd_sources(args, notes)
        for step in (cmd_packs, cmd_render, cmd_sources):
            rc = step(args, notes)
            if rc:
                print("stopping: %s failed" % step.__name__[4:], file=sys.stderr)
                return rc
        return 0
    except FatalError as e:
        print("ERROR: %s" % e, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
