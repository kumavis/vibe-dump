class Note:
    def __init__(self, d, path, caption_source):
        self.d = d
        self.path = path
        self.id = d["id"]
        self.video_id = d.get("video_id") or self.id.split("@")[0]
        seg = d.get("segment")
        if isinstance(seg, dict) and "start" in seg:
            self.start = int(seg["start"])
        elif "@" in self.id:
            self.start = int(self.id.split("@", 1)[1])
        else:
            self.start = None
        self.is_segment = "@" in self.id
        self.title = d["title"]
        self.speaker = d["speaker"]
        self.year = d["year"]
        self.insights = d["insights"]
        self.caption_source = caption_source

    @property
    def video_url(self):
        if self.is_segment:
            return "https://youtu.be/%s?t=%d" % (self.video_id, self.start or 0)
        return "https://youtu.be/%s" % self.video_id


def load_notes(notes_dir, transcripts_dir):
    if not os.path.isdir(notes_dir):
        raise FatalError("notes directory not found: %s" % notes_dir)
    notes, problems, captions = {}, [], {}
    for path in sorted(glob.glob(os.path.join(notes_dir, "*.json"))):
        rel = os.path.basename(path)
        try:
            with open(path, encoding="utf-8") as f:
                d = json.load(f)
        except (OSError, ValueError) as e:
            problems.append("%s: cannot parse JSON (%s)" % (rel, e))
            continue
        if not isinstance(d, dict) or not isinstance(d.get("insights"), list):
            continue  # not a note file (e.g. batches.json)
        missing = [k for k in NOTE_FIELDS if k not in d]
        if missing:
            problems.append("%s: missing field(s) %s" % (rel, ", ".join(missing)))
            continue
        stem = rel[:-len(".json")]
        if d["id"] != stem:
            problems.append("%s: \"id\" is %r but the file name says %r" % (rel, d["id"], stem))
            continue
        if not KEY_RE.match(d["id"] + "#0"):
            problems.append("%s: note id %r is not a valid id" % (rel, d["id"]))
            continue
        bad = False
        for i, ins in enumerate(d["insights"]):
            miss = [k for k in INSIGHT_FIELDS if k not in ins]
            if miss:
                problems.append("%s: insight #%d missing %s" % (rel, i, ", ".join(miss)))
                bad = True
            elif ins["topic"] not in TOPICS:
                problems.append("%s: insight #%d has unknown topic %r" % (rel, i, ins["topic"]))
                bad = True
        if bad:
            continue
        vid = d.get("video_id") or d["id"].split("@")[0]
        if vid not in captions:
            captions[vid] = None
            tp = os.path.join(transcripts_dir, vid + ".json")
            try:
                with open(tp, encoding="utf-8") as f:
                    captions[vid] = json.load(f).get("caption_source")
            except (OSError, ValueError):
                pass
        notes[d["id"]] = Note(d, path, captions[vid])
    if problems:
        raise FatalError("problems in notes files:\n  " + "\n  ".join(problems))
    if not notes:
        raise FatalError("no note files found in %s" % notes_dir)
    return notes


