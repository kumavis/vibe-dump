WORD_RE = re.compile(r"[^\W_]+(?:['’.\-][^\W_]+)*")


def prose_words(s):
    s = TOKEN_RE.sub(" ", s)
    s = re.sub(r"<!--.*?-->", " ", s, flags=re.S)
    s = re.sub(r"\]\([^)]*\)", "]", s)  # drop link targets
    return WORD_RE.findall(s)


def uncited_prose(doc, skip_ranges):
    """Warnings for paragraphs / list items over UNCITED_PROSE_WORDS words with no key.
    skip_ranges: [(first_line, end_line_exclusive)] of 1-based lines to ignore."""
    blocks = []  # (start_line, [lines])
    cur = None
    for i, ln in enumerate(doc.lines):
        stripped = ln.strip()
        boundary = (i in doc.fenced_lines or not stripped or HEADING_RE.match(ln)
                    or BQ_RE.match(ln) or stripped.startswith("|") or stripped.startswith("<!--"))
        if boundary:
            cur = None
            continue
        if LIST_RE.match(ln) or cur is None:
            cur = (i + 1, [ln])
            blocks.append(cur)
        else:
            cur[1].append(ln)
    out = []
    for start, lines in blocks:
        if any(s <= start < e for s, e in skip_ranges):
            continue
        body = "\n".join(lines)
        if "{{" in body:
            continue
        w = prose_words(LIST_RE.sub("", body, count=1))
        if len(w) > UNCITED_PROSE_WORDS:
            out.append((start, "uncited prose (%d words): \"%s …\"" % (len(w), " ".join(w[:12]))))
    return out


def chapter_report(path, notes, bible_dir):
    name = os.path.basename(path)
    text = read(path)
    a = analyse(name, text, notes)
    doc = a["doc"]
    num = int(name[:2])
    spec_fn, topic = CHAPTER_BY_NUM.get(num, (None, None))
    errors = list(a["errors"])
    warnings = []
    if spec_fn and spec_fn != name:
        warnings.append((1, "file name differs from SPEC.md, which expects src/%s" % spec_fn))

    # word count: prose outside fenced code
    prose = "\n".join(ln for i, ln in enumerate(doc.lines) if i not in doc.fenced_lines)
    words = len(prose_words(prose))

    cited = collections.OrderedDict()
    for _, note, n in a["cites"]:
        cited[(note.id, n)] = note
    talks = {k[0] for k in cited}

    rep = {"chapter": name, "number": num, "topic": topic, "words": words,
           "citations": len(a["cites"]), "distinct_insights": len(cited),
           "distinct_talks": len(talks)}

    # coverage
    if topic:
        cov = {}
        uncited_w3 = []
        for w in (3, 2, 1):
            tot = hit = 0
            for note in notes.values():
                for n, ins in enumerate(note.insights):
                    if ins["topic"] == topic and ins["weight"] == w:
                        tot += 1
                        if (note.id, n) in cited:
                            hit += 1
                        elif w == 3:
                            uncited_w3.append((note.year, note.id, n, ins))
            cov["w%d" % w] = {"cited": hit, "total": tot}
        uncited_w3.sort(key=lambda x: (norm_subtopic(x[3]["subtopic"]), x[0], x[1], x[2]))
        rep["coverage"] = cov
        rep["uncited_w3"] = [{"key": "%s#%d" % (nid, n), "subtopic": norm_subtopic(ins["subtopic"]),
                              "claim": ins["claim"][:80]} for _, nid, n, ins in uncited_w3]
        rep["from_other_topics"] = sum(1 for (nid, n), note in cited.items()
                                       if note.insights[n]["topic"] != topic)
    else:
        rep["coverage"] = None
        rep["uncited_w3"] = []
        rep["from_other_topics"] = None

    # sections
    heads = doc.headings()
    h2 = {h[2].lower() for h in heads if h[1] == 2}
    sections = {s: (s.lower() in h2) for s in REQUIRED_SECTIONS}
    rep["sections"] = sections
    if num != 0:
        for s, ok in sections.items():
            if not ok:
                errors.append((0, "missing required section '## %s'" % s))

    # uncited prose
    first_h2 = next((h[0] for h in heads if h[1] == 2), len(doc.lines) + 1)
    skip_ranges = [(1, first_h2)]
    for idx, (ln, lvl, title) in enumerate(heads):
        if lvl == 2 and title.lower() in ("checklist", "see also"):
            end = next((h[0] for h in heads[idx + 1:] if h[1] <= 2), len(doc.lines) + 1)
            skip_ranges.append((ln, end))
    warnings += uncited_prose(doc, skip_ranges)

    # outline (if the architect has written one)
    rep["outline"] = None
    opath = os.path.join(bible_dir, "outlines", "%02d.json" % num)
    if os.path.exists(opath):
        try:
            with open(opath, encoding="utf-8") as f:
                od = json.load(f)
            assigned = []
            for sec in od.get("sections") or []:
                for k in sec.get("keys") or []:
                    note, n, problem = key_problem(k, notes) if isinstance(k, str) else (None, None, 1)
                    if note is not None:
                        assigned.append((note, n, sec.get("heading")))
        except (OSError, ValueError, AttributeError, TypeError) as e:
            warnings.append((0, "outlines/%02d.json could not be read (%s); run partpack %02d to "
                                "validate it" % (num, e, num)))
        else:
            seen = set()
            miss = {3: [], 2: [], 1: []}
            for note, n, heading in assigned:
                if (note.id, n) in seen or (note.id, n) in cited:
                    continue
                seen.add((note.id, n))
                ins = note.insights[n]
                miss.setdefault(ins["weight"], []).append(
                    {"key": "%s#%d" % (note.id, n), "section": heading,
                     "subtopic": norm_subtopic(ins["subtopic"]), "claim": ins["claim"][:80]})
            total = {}
            for note, n, _ in assigned:
                total.setdefault(note.insights[n]["weight"], set()).add((note.id, n))
            rep["outline"] = {
                "path": "outlines/%02d.json" % num,
                "assigned": {"w%d" % w: len(total.get(w, ())) for w in (3, 2, 1)},
                "assigned_uncited": {"w%d" % w: len(miss.get(w, [])) for w in (3, 2, 1)},
                "uncited_w3": miss.get(3, []),
            }

    rep["errors"] = [{"line": l, "message": m} for l, m in sorted(errors, key=lambda e: e[0])]
    rep["warnings"] = [{"line": l, "message": m} for l, m in sorted(warnings, key=lambda e: e[0])]
    return rep


