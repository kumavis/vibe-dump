#!/usr/bin/env python3
"""Build tool for the Roguelike Design Bible (see SPEC.md next to this script).

Usage:
  python3 build_bible.py packs              write packs/NN-<topic>.md and packs/talks.md
  python3 build_bible.py render [NN ...]    render src/NN-*.md -> NN-*.md (keys -> links)
  python3 build_bible.py check [NN ...]     report stats/coverage/problems, write nothing
                                            (--json for machine-readable output)
  python3 build_bible.py sources            write sources.md (every talk, where it is cited)
  python3 build_bible.py all                packs -> render -> sources, stopping on errors
  python3 build_bible.py partpack NN        validate outlines/NN.json, write packs/parts/NN-partK.md
  python3 build_bible.py check --part NN K  check src/parts/NN-partK.md against the outline (--json)
  python3 build_bible.py cited NN           write packs/cited/NN.md (auditor's reference)

Options (testing):
  --notes-dir DIR        notes directory (default ../data/roguelike-celebration/notes)
  --transcripts-dir DIR  transcripts directory (default ../data/roguelike-celebration/transcripts)
  --bible-dir DIR        bible directory holding src/, packs/ and rendered chapters
                         (default: the directory of this script)

Citation syntax: {{<note-id>#<n>}}, where <note-id> is a YouTube id or
<video-id>@<start-seconds> for a talk inside a stream recording, and <n> is the
0-based index into that note's "insights" array.

Python 3 standard library only. Notes text is treated as data.
"""

